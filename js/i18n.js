window.t = function (key) {
  const d = I18N.dyn[key];
  if (d) return d[I18N.lang] || d.de;
  return key;
};

window.applyStatic = function () {
  const en = I18N.lang === 'en';
  document.documentElement.lang = I18N.lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    if (el.dataset.de === undefined) el.dataset.de = el.innerHTML;
    const k = el.dataset.i18n;
    const txt = en ? (I18N.en[k] || (I18N.dyn[k] && I18N.dyn[k].en)) : null;
    el.innerHTML = txt || el.dataset.de;
  });
};

window.setLang = function (lang) {
  I18N.lang = lang;
  try { localStorage.setItem('lang', lang); } catch (e) { /* storage unavailable */ }
  applyStatic();
  document.dispatchEvent(new CustomEvent('langchange'));
  if (window.hydrateIcons) hydrateIcons();
};
